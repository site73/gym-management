-- =============================================================
-- V12：超级管理员角色 + 账号密码重置留痕
-- 背景：
--   1) 需要"最高权限"角色来统一管理全部账号（查看账号、重置密码、停用账号）
--   2) 注册功能上线后账号数量增长较快，需要一个集中入口来审计与治理
-- 说明：
--   密码仍以 BCrypt 哈希存储（不可逆）。系统不提供"查看明文密码"的能力，
--   而是提供"重置密码"：重置后返回新密码，既满足"知道密码是什么"的实际需要，
--   又不破坏密码存储的安全前提。password_reset_at 用于审计"该账号密码何时被重置"。
-- =============================================================

SET NAMES utf8mb4;

-- ---------- 超级管理员角色 ----------
INSERT INTO sys_role (code, name) VALUES ('super_admin', '超级管理员')
  ON DUPLICATE KEY UPDATE name = VALUES(name);

-- ---------- 密码重置留痕 ----------
ALTER TABLE sys_user
  ADD COLUMN password_reset_at DATETIME NULL COMMENT '最近一次密码重置时间' AFTER password_hash;
